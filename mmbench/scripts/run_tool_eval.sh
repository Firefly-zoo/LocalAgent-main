#!/usr/bin/env bash
set -euo pipefail

THIS_DIR=$(cd "$(dirname "$0")" && pwd)
PROJECT_ROOT=$(cd "$THIS_DIR/.." && pwd)

CONFIG=${CONFIG:-$PROJECT_ROOT/configs/pair_eval.yaml}
ADAPTER_PATH=${ADAPTER_PATH:-}
QUESTION_SCOPE=${QUESTION_SCOPE:-all}
WORK_DIR=${WORK_DIR:-$PROJECT_ROOT/outputs/tool_eval_${QUESTION_SCOPE}}
PYTHON_BIN=${PYTHON_BIN:-python3}
SWIFT_SRC_ROOT=${SWIFT_SRC_ROOT:-$PROJECT_ROOT/../ms-swift}
XFEAT_TOOL_BACKEND=${XFEAT_TOOL_BACKEND:-xfeat}
XFEAT_TOOL_ROOT=${XFEAT_TOOL_ROOT:-$PROJECT_ROOT/../accelerated_features}
XFEAT_TOOL_WEIGHTS=${XFEAT_TOOL_WEIGHTS:-}
XFEAT_TOOL_TOP_K=${XFEAT_TOOL_TOP_K:-256}
XFEAT_TOOL_MIN_COSSIM=${XFEAT_TOOL_MIN_COSSIM:-0.80}
XFEAT_TOOL_DETECTION_THRESHOLD=${XFEAT_TOOL_DETECTION_THRESHOLD:-0.03}
XFEAT_TOOL_CONTEXT_RATIO=${XFEAT_TOOL_CONTEXT_RATIO:-0.08}
XFEAT_TOOL_CANVAS_SIZE=${XFEAT_TOOL_CANVAS_SIZE:-256}
XFEAT_TOOL_GRID_SIZE=${XFEAT_TOOL_GRID_SIZE:-4}

CMD=(
  "$PYTHON_BIN" "$PROJECT_ROOT/scripts/eval_tool.py"
  --config "$CONFIG"
  --question-scope "$QUESTION_SCOPE"
  --work-dir "$WORK_DIR"
)
if [[ -n "$ADAPTER_PATH" ]]; then
  CMD+=(--adapter "$ADAPTER_PATH")
fi

ENV_ARGS=(
  LOG_LEVEL=${LOG_LEVEL:-WARNING}
  PYTHONPATH="$SWIFT_SRC_ROOT${PYTHONPATH:+:$PYTHONPATH}"
  TWIN_LOCAL_GEOM_BACKEND="$XFEAT_TOOL_BACKEND"
  TWIN_LOCAL_GEOM_XFEAT_ROOT="$XFEAT_TOOL_ROOT"
  TWIN_LOCAL_GEOM_XFEAT_TOP_K="$XFEAT_TOOL_TOP_K"
  TWIN_LOCAL_GEOM_XFEAT_MIN_COSSIM="$XFEAT_TOOL_MIN_COSSIM"
  TWIN_LOCAL_GEOM_XFEAT_DETECTION_THRESHOLD="$XFEAT_TOOL_DETECTION_THRESHOLD"
  TWIN_LOCAL_GEOM_CONTEXT_RATIO="$XFEAT_TOOL_CONTEXT_RATIO"
  TWIN_LOCAL_GEOM_CANVAS_SIZE="$XFEAT_TOOL_CANVAS_SIZE"
  TWIN_LOCAL_GEOM_GRID_SIZE="$XFEAT_TOOL_GRID_SIZE"
)

if [[ -n "$XFEAT_TOOL_WEIGHTS" ]]; then
  ENV_ARGS+=(TWIN_LOCAL_GEOM_XFEAT_WEIGHTS="$XFEAT_TOOL_WEIGHTS")
fi

cd "$PROJECT_ROOT"
env "${ENV_ARGS[@]}" "${CMD[@]}"
