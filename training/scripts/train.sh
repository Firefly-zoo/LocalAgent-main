#!/usr/bin/env bash
set -euo pipefail

THIS_DIR=$(cd "$(dirname "$0")" && pwd)
PROJECT_ROOT=$(cd "$THIS_DIR/.." && pwd)
REPO_ROOT=$(cd "$PROJECT_ROOT/.." && pwd)
TRAIN_CONFIG=${TRAIN_CONFIG:-$PROJECT_ROOT/configs/main.env}
if [[ -f "$TRAIN_CONFIG" ]]; then
  source "$TRAIN_CONFIG"
fi
SWIFT_SRC_ROOT=${SWIFT_SRC_ROOT:-$REPO_ROOT/ms-swift}
PYTHON_BIN=${PYTHON_BIN:-python3}
RLHF_CLI=${RLHF_CLI:-$SWIFT_SRC_ROOT/swift/cli/rlhf.py}

PLUGIN_PATH="$PROJECT_ROOT/plugins/structure_plugin.py"
PROMPT_PATH="$PROJECT_ROOT/prompts/localagent_rft.txt"
AGENT_TEMPLATE=${AGENT_TEMPLATE:-hermes}

MODEL_PATH=${MODEL_PATH:-$REPO_ROOT/models/Qwen3-VL-4B-Instruct}
TRAIN_DATA=${TRAIN_DATA:-$REPO_ROOT/data/training/ms_swift/tool/train.jsonl}
VAL_DATA=${VAL_DATA:-$REPO_ROOT/data/training/ms_swift/tool/val.jsonl}
OUTPUT_DIR=${OUTPUT_DIR:-$REPO_ROOT/outputs/training/localagent_grpo}
DINO_TOOL_MODEL_PATH=${DINO_TOOL_MODEL_PATH:-$REPO_ROOT/models/dinov2-small-local}
DINO_TOOL_DEVICE=${DINO_TOOL_DEVICE:-cuda}
DINO_TOOL_BATCH_SIZE=${DINO_TOOL_BATCH_SIZE:-8}
VLLM_SERVER_HOST=${VLLM_SERVER_HOST:-127.0.0.1}
VLLM_SERVER_PORT=${VLLM_SERVER_PORT:-8000}
VLLM_SERVER_GROUP_PORT=${VLLM_SERVER_GROUP_PORT:-51216}
MAX_PIXELS=${MAX_PIXELS:-451584}
MIN_PIXELS=${MIN_PIXELS:-3136}
IMAGE_MAX_TOKEN_NUM=${IMAGE_MAX_TOKEN_NUM:-$((MAX_PIXELS / 784))}
VIDEO_MAX_TOKEN_NUM=${VIDEO_MAX_TOKEN_NUM:-128}
PYTORCH_CUDA_ALLOC_CONF=${PYTORCH_CUDA_ALLOC_CONF:-expandable_segments:True}
MAX_LENGTH=${MAX_LENGTH:-4096}
MAX_COMPLETION_LENGTH=${MAX_COMPLETION_LENGTH:-256}
PER_DEVICE_TRAIN_BATCH_SIZE=${PER_DEVICE_TRAIN_BATCH_SIZE:-8}
GRADIENT_ACCUMULATION_STEPS=${GRADIENT_ACCUMULATION_STEPS:-1}
NUM_GENERATIONS=${NUM_GENERATIONS:-8}
MAX_GRAD_NORM=${MAX_GRAD_NORM:-0.5}
LEARNING_RATE=${LEARNING_RATE:-1e-5}
MAX_TURNS=${MAX_TURNS:-2}
TEMPERATURE=${TEMPERATURE:-0.7}
TRAIN_CUDA_VISIBLE_DEVICES=${TRAIN_CUDA_VISIBLE_DEVICES:-${CUDA_VISIBLE_DEVICES:-0,1,2,3}}
TRAIN_NPROC_PER_NODE=${TRAIN_NPROC_PER_NODE:-${NPROC_PER_NODE:-4}}
STEPS_PER_GENERATION=${STEPS_PER_GENERATION:-$GRADIENT_ACCUMULATION_STEPS}
STOP_WORDS=${STOP_WORDS:-}
PADDING_FREE=${PADDING_FREE:-true}
GRADIENT_CHECKPOINTING=${GRADIENT_CHECKPOINTING:-true}
VIT_GRADIENT_CHECKPOINTING=${VIT_GRADIENT_CHECKPOINTING:-false}
LOSS_SCALE=${LOSS_SCALE:-default+hermes}
LOGGING_STEPS=${LOGGING_STEPS:-10}
LOG_COMPLETIONS=${LOG_COMPLETIONS:-true}
DATALOADER_NUM_WORKERS=${DATALOADER_NUM_WORKERS:-8}
DATASET_NUM_PROC=${DATASET_NUM_PROC:-8}
SPLIT_DATASET_RATIO=${SPLIT_DATASET_RATIO:-0.0}
SAVE_STEPS=${SAVE_STEPS:-50}
SAVE_TOTAL_LIMIT=${SAVE_TOTAL_LIMIT:-}
EVAL_STRATEGY=${EVAL_STRATEGY:-steps}
EVAL_STEPS=${EVAL_STEPS:-50}
PER_DEVICE_EVAL_BATCH_SIZE=${PER_DEVICE_EVAL_BATCH_SIZE:-$PER_DEVICE_TRAIN_BATCH_SIZE}
NUM_GENERATIONS_EVAL=${NUM_GENERATIONS_EVAL:-$NUM_GENERATIONS}
REWARD_FUNCS=${REWARD_FUNCS:-"twin_dino_structure_tool_family_total"}
REWARD_WEIGHTS=${REWARD_WEIGHTS:-"1.0"}
TWIN_DINO_STRUCTURE_TOOL_FAMILY_ANSWER_WEIGHT=${TWIN_DINO_STRUCTURE_TOOL_FAMILY_ANSWER_WEIGHT:-1.0}
TWIN_DINO_STRUCTURE_TOOL_FAMILY_USAGE_WEIGHT=${TWIN_DINO_STRUCTURE_TOOL_FAMILY_USAGE_WEIGHT:-0.15}
TWIN_DINO_STRUCTURE_TOOL_FAMILY_VALIDITY_WEIGHT=${TWIN_DINO_STRUCTURE_TOOL_FAMILY_VALIDITY_WEIGHT:-0.10}
TWIN_DINO_STRUCTURE_TOOL_FAMILY_FORMAT_WEIGHT=${TWIN_DINO_STRUCTURE_TOOL_FAMILY_FORMAT_WEIGHT:-0.05}
TWIN_DINO_STRUCTURE_TOOL_FAMILY_EFFICIENCY_WEIGHT=${TWIN_DINO_STRUCTURE_TOOL_FAMILY_EFFICIENCY_WEIGHT:-0.05}
TWIN_DINO_STRUCTURE_TOOL_FAMILY_WRONG_AUX_CAP=${TWIN_DINO_STRUCTURE_TOOL_FAMILY_WRONG_AUX_CAP:-0.06}
TWIN_DINO_STRUCTURE_TOOL_FAMILY_WRONG_AUX_FLOOR=${TWIN_DINO_STRUCTURE_TOOL_FAMILY_WRONG_AUX_FLOOR:--0.12}
NUM_TRAIN_EPOCHS=${NUM_TRAIN_EPOCHS:-1}
MAX_STEPS=${MAX_STEPS:-}
RESUME_FROM_CHECKPOINT=${RESUME_FROM_CHECKPOINT:-}

read -r -a REWARD_FUNC_ARGS <<< "$REWARD_FUNCS"
read -r -a REWARD_WEIGHT_ARGS <<< "$REWARD_WEIGHTS"

if [[ ${#REWARD_FUNC_ARGS[@]} -ne ${#REWARD_WEIGHT_ARGS[@]} ]]; then
  echo "REWARD_FUNCS and REWARD_WEIGHTS must have the same length." >&2
  exit 1
fi

if [[ "$GRADIENT_CHECKPOINTING" == "true" ]]; then
  GRADIENT_CHECKPOINTING_ARGS=(--gradient_checkpointing_kwargs '{"use_reentrant": false}')
else
  GRADIENT_CHECKPOINTING_ARGS=()
fi

CMD=(
  "$PYTHON_BIN" -m torch.distributed.run
  --nproc_per_node "$TRAIN_NPROC_PER_NODE"
  "$RLHF_CLI"
  --rlhf_type grpo
  --model "$MODEL_PATH"
  --external_plugins "$PLUGIN_PATH"
  --agent_template "$AGENT_TEMPLATE"
  --multi_turn_scheduler twin_dino_structure_tool_family_call_scheduler
  --reward_funcs "${REWARD_FUNC_ARGS[@]}"
  --reward_weights "${REWARD_WEIGHT_ARGS[@]}"
  --use_vllm true
  --vllm_mode server
  --vllm_server_host "$VLLM_SERVER_HOST"
  --vllm_server_port "$VLLM_SERVER_PORT"
  --vllm_server_group_port "$VLLM_SERVER_GROUP_PORT"
  --vllm_server_pass_dataset true
  --max_turns "$MAX_TURNS"
  --tuner_type lora
  --lora_rank 16
  --lora_alpha 32
  --lora_dropout 0.05
  --target_modules all-linear
  --freeze_vit true
  --freeze_aligner true
  --gradient_checkpointing "$GRADIENT_CHECKPOINTING"
  --vit_gradient_checkpointing "$VIT_GRADIENT_CHECKPOINTING"
  --loss_scale "$LOSS_SCALE"
  --torch_dtype bfloat16
  --attn_impl flash_attention_2
  --max_pixels "$MAX_PIXELS"
  --dataset "$TRAIN_DATA"
  --split_dataset_ratio "$SPLIT_DATASET_RATIO"
  --load_from_cache_file true
  --system "$PROMPT_PATH"
  --max_length "$MAX_LENGTH"
  --max_completion_length "$MAX_COMPLETION_LENGTH"
  --num_train_epochs "$NUM_TRAIN_EPOCHS"
  --seed 42
  --data_seed 42
  --per_device_train_batch_size "$PER_DEVICE_TRAIN_BATCH_SIZE"
  --gradient_accumulation_steps "$GRADIENT_ACCUMULATION_STEPS"
  --steps_per_generation "$STEPS_PER_GENERATION"
  --learning_rate "$LEARNING_RATE"
  --weight_decay 0.1
  --optim adamw_torch_fused
  --adam_beta1 0.9
  --adam_beta2 0.95
  --adam_epsilon 1e-8
  --lr_scheduler_type cosine
  --beta 0.04
  --kl_in_reward false
  --epsilon 0.2
  --scale_rewards group
  --loss_type grpo
  --save_strategy steps
  --save_steps "$SAVE_STEPS"
  --eval_strategy "$EVAL_STRATEGY"
  --eval_steps "$EVAL_STEPS"
  --per_device_eval_batch_size "$PER_DEVICE_EVAL_BATCH_SIZE"
  --num_generations_eval "$NUM_GENERATIONS_EVAL"
  --logging_steps "$LOGGING_STEPS"
  --output_dir "$OUTPUT_DIR"
  --warmup_ratio 0.05
  --dataloader_num_workers "$DATALOADER_NUM_WORKERS"
  --dataset_num_proc "$DATASET_NUM_PROC"
  --num_generations "$NUM_GENERATIONS"
  --temperature "$TEMPERATURE"
  --top_p 1.0
  --top_k -1
  --repetition_penalty 1.0
  --max_grad_norm "$MAX_GRAD_NORM"
  --padding_free "$PADDING_FREE"
)
if [[ -n "$MAX_STEPS" ]]; then
  CMD+=(--max_steps "$MAX_STEPS")
fi
if [[ -n "$SAVE_TOTAL_LIMIT" ]]; then
  CMD+=(--save_total_limit "$SAVE_TOTAL_LIMIT")
fi
if [[ -n "$STOP_WORDS" ]]; then
  CMD+=(--stop_words "$STOP_WORDS")
fi
if [[ -n "$VAL_DATA" ]]; then
  CMD+=(--val_dataset "$VAL_DATA")
fi
if [[ "$LOG_COMPLETIONS" == "true" ]]; then
  CMD+=(--log_completions true)
fi
if [[ -n "$RESUME_FROM_CHECKPOINT" ]]; then
  CMD+=(--resume_from_checkpoint "$RESUME_FROM_CHECKPOINT")
fi
CMD+=("${GRADIENT_CHECKPOINTING_ARGS[@]}")

LOG_LEVEL=WARNING \
PYTHONPATH="$SWIFT_SRC_ROOT${PYTHONPATH:+:$PYTHONPATH}" \
PYTORCH_CUDA_ALLOC_CONF="$PYTORCH_CUDA_ALLOC_CONF" \
IMAGE_MAX_TOKEN_NUM="$IMAGE_MAX_TOKEN_NUM" \
VIDEO_MAX_TOKEN_NUM="$VIDEO_MAX_TOKEN_NUM" \
MIN_PIXELS="$MIN_PIXELS" \
TWIN_DINO_PATCH_MNN_MODEL_PATH="$DINO_TOOL_MODEL_PATH" \
TWIN_DINO_PATCH_MNN_DEVICE="$DINO_TOOL_DEVICE" \
TWIN_DINO_PATCH_MNN_BATCH_SIZE="$DINO_TOOL_BATCH_SIZE" \
TWIN_DINO_STRUCTURE_TOOL_FAMILY_ANSWER_WEIGHT="$TWIN_DINO_STRUCTURE_TOOL_FAMILY_ANSWER_WEIGHT" \
TWIN_DINO_STRUCTURE_TOOL_FAMILY_USAGE_WEIGHT="$TWIN_DINO_STRUCTURE_TOOL_FAMILY_USAGE_WEIGHT" \
TWIN_DINO_STRUCTURE_TOOL_FAMILY_VALIDITY_WEIGHT="$TWIN_DINO_STRUCTURE_TOOL_FAMILY_VALIDITY_WEIGHT" \
TWIN_DINO_STRUCTURE_TOOL_FAMILY_FORMAT_WEIGHT="$TWIN_DINO_STRUCTURE_TOOL_FAMILY_FORMAT_WEIGHT" \
TWIN_DINO_STRUCTURE_TOOL_FAMILY_EFFICIENCY_WEIGHT="$TWIN_DINO_STRUCTURE_TOOL_FAMILY_EFFICIENCY_WEIGHT" \
TWIN_DINO_STRUCTURE_TOOL_FAMILY_WRONG_AUX_CAP="$TWIN_DINO_STRUCTURE_TOOL_FAMILY_WRONG_AUX_CAP" \
TWIN_DINO_STRUCTURE_TOOL_FAMILY_WRONG_AUX_FLOOR="$TWIN_DINO_STRUCTURE_TOOL_FAMILY_WRONG_AUX_FLOOR" \
CUDA_VISIBLE_DEVICES="$TRAIN_CUDA_VISIBLE_DEVICES" \
"${CMD[@]}"
